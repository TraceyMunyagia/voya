import '../../core/constants/enums.dart';
import 'cost.dart';
import 'item_link.dart';
import 'place_ref.dart';

/// One entry inside a day. All categories share this shape;
/// category-specific fields live in [details].
/// accommodation: {nights, stay_type}
/// transport:     {mode, provider, from, to}
/// meal:          {meal_type, source: eating_out|self_catered|private_chef, food}
/// activity:      {activity_type}
class ItineraryItem {
  const ItineraryItem({
    required this.id,
    required this.tripId,
    required this.dayId,
    required this.category,
    required this.title,
    this.description = '',
    this.cost = const Cost(),
    this.location,
    this.links = const [],
    this.photoUrls = const [],
    this.notes = '',
    this.rating,
    this.sortOrder = 0,
    this.details = const {},
  });

  final String id;
  final String tripId;
  final String dayId;
  final ItemCategory category;
  final String title;
  final String description;
  final Cost cost;
  final PlaceRef? location;
  final List<ItemLink> links;
  final List<String> photoUrls;
  final String notes;
  final int? rating; // 1-5
  final int sortOrder;
  final Map<String, dynamic> details;

  /// Row to insert or update (the id is generated by the database).
  Map<String, dynamic> toJson() => {
    'trip_id': tripId,
    'day_id': dayId,
    'category': category.name,
    'title': title,
    'description': description,
    ...cost.toColumns(),
    'location': location?.toJson(),
    'links': links.map((l) => l.toJson()).toList(),
    'photo_urls': photoUrls,
    'notes': notes,
    'rating': rating,
    'sort_order': sortOrder,
    'details': details,
  };

  factory ItineraryItem.fromJson(Map<String, dynamic> m) => ItineraryItem(
    id: m['id'] as String,
    tripId: m['trip_id'] as String,
    dayId: m['day_id'] as String,
    category: enumFromName(
      ItemCategory.values,
      m['category'] as String?,
      ItemCategory.other,
    ),
    title: m['title'] as String? ?? '',
    description: m['description'] as String? ?? '',
    cost: Cost.fromColumns(m),
    location: m['location'] == null
        ? null
        : PlaceRef.fromJson(Map<String, dynamic>.from(m['location'] as Map)),
    links: ((m['links'] as List?) ?? [])
        .map((e) => ItemLink.fromJson(Map<String, dynamic>.from(e as Map)))
        .toList(),
    photoUrls: List<String>.from((m['photo_urls'] as List?) ?? []),
    notes: m['notes'] as String? ?? '',
    rating: (m['rating'] as num?)?.toInt(),
    sortOrder: (m['sort_order'] as num?)?.toInt() ?? 0,
    details: Map<String, dynamic>.from((m['details'] as Map?) ?? {}),
  );
}
